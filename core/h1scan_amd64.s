TEXT ·firstH1SpecialAVX2(SB), NOSPLIT, $0-24
	MOVQ p+0(FP), SI
	MOVQ n+8(FP), CX
	XORQ AX, AX
	CMPQ CX, $32
	JL   tail
	VMOVDQU h1ctlmax<>(SB), Y5
	VMOVDQU h1tab<>(SB), Y6
	VMOVDQU h1del<>(SB), Y7

loop:
	MOVQ AX, DX
	ADDQ $32, DX
	CMPQ DX, CX
	JG   vtail
	VMOVDQU  (SI)(AX*1), Y0
	VPMINUB  Y5, Y0, Y1
	VPCMPEQB Y0, Y1, Y1
	VPCMPEQB Y6, Y0, Y2
	VPXOR    Y2, Y1, Y1
	VPCMPEQB Y7, Y0, Y3
	VPOR     Y3, Y1, Y1
	VPMOVMSKB Y1, BX
	TESTL    BX, BX
	JNZ      vfound
	ADDQ     $32, AX
	JMP      loop

vfound:
	BSFL BX, BX
	ADDQ BX, AX
	VZEROUPPER
	MOVQ AX, ret+16(FP)
	RET

vtail:
	CMPQ AX, CX
	JGE  vnotfound
	MOVQ CX, DI
	SUBQ $32, DI
	VMOVDQU  (SI)(DI*1), Y0
	VPMINUB  Y5, Y0, Y1
	VPCMPEQB Y0, Y1, Y1
	VPCMPEQB Y6, Y0, Y2
	VPXOR    Y2, Y1, Y1
	VPCMPEQB Y7, Y0, Y3
	VPOR     Y3, Y1, Y1
	VPMOVMSKB Y1, BX
	MOVQ AX, CX
	SUBQ DI, CX
	SHRL CX, BX
	TESTL BX, BX
	JZ   vnotfound
	BSFL BX, BX
	ADDQ BX, AX
	VZEROUPPER
	MOVQ AX, ret+16(FP)
	RET

vnotfound:
	VZEROUPPER
	MOVQ $-1, ret+16(FP)
	RET

tail:
	CMPQ AX, CX
	JGE  notfound
	MOVBLZX (SI)(AX*1), DX
	CMPB DL, $0x7F
	JE   found
	CMPB DL, $0x1F
	JA   next
	CMPB DL, $0x09
	JNE  found

next:
	INCQ AX
	JMP  tail

found:
	MOVQ AX, ret+16(FP)
	RET

notfound:
	MOVQ $-1, ret+16(FP)
	RET

