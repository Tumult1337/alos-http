#define BLK_NONTOKEN(src, dst) \
	VPAND    Y11, src, dst; \
	VPSRLW   $4, src, Y3; \
	VPAND    Y11, Y3, Y3; \
	VPSHUFB  dst, Y9, dst; \
	VPSHUFB  Y3, Y10, Y3; \
	VPAND    Y3, dst, dst; \
	VPCMPEQB Y8, dst, dst

#define BLK_BADCTL(src) \
	VPCMPEQB Y12, src, Y3; \
	VPCMPEQB Y13, src, Y4; \
	VPOR     Y3, Y4, Y4; \
	VPMINUB  Y5, src, Y2; \
	VPCMPEQB src, Y2, Y2; \
	VPCMPEQB Y6, src, Y3; \
	VPXOR    Y3, Y2, Y2; \
	VPCMPEQB Y7, src, Y3; \
	VPOR     Y3, Y2, Y2; \
	VPANDN   Y2, Y4, Y2; \
	VPTEST   Y2, Y2

#define BLK_MASK64(cmplo, cmphi, dst) \
	VPMOVMSKB cmplo, dst; \
	VPMOVMSKB cmphi, BX; \
	SHLQ      $32, BX; \
	ORQ       BX, dst

