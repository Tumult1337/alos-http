bchunk:
	MOVQ CX, BX
	SUBQ AX, BX
	JLE  bdone
	CMPQ BX, $64
	JL   btailprep
	VMOVDQU (SI)(AX*1), Y0
	VMOVDQU 32(SI)(AX*1), Y1
	ADDQ    $64, AX
	JMP     bprocess

btailprep:
	MOVQ    BX, CX
	MOVQ    $1, DX
	SHLQ    CX, DX
	DECQ    DX
	MOVQ    DX, 64(SP)
	VMOVDQU h1blkpad<>(SB), Y15
	VMOVDQU Y15, 0(SP)
	VMOVDQU Y15, 32(SP)
	LEAQ    (SI)(AX*1), R14
	XORQ    R13, R13

btailcopy8:
	LEAQ 8(R13), DX
	CMPQ DX, CX
	JG   btailcopy1
	MOVQ (R14)(R13*1), DX
	MOVQ DX, (SP)(R13*1)
	ADDQ $8, R13
	JMP  btailcopy8

btailcopy1:
	CMPQ    R13, CX
	JGE     btailloaded
	MOVBLZX (R14)(R13*1), DX
	MOVB    DX, (SP)(R13*1)
	INCQ    R13
	JMP     btailcopy1

btailloaded:
	ADDQ    CX, AX
	MOVQ    AX, CX
	VMOVDQU 0(SP), Y0
	VMOVDQU 32(SP), Y1

bprocess:
	BLK_BADCTL(Y0)
	JNZ bfail
	BLK_BADCTL(Y1)
	JNZ bfail

	BLK_NONTOKEN(Y0, Y2)
	BLK_NONTOKEN(Y1, Y4)
	BLK_MASK64(Y2, Y4, R14)
	NOTQ R14

	VPCMPEQB Y12, Y0, Y2
	VPCMPEQB Y12, Y1, Y4
	BLK_MASK64(Y2, Y4, DX)

	VPCMPEQB Y13, Y0, Y2
	VPCMPEQB Y13, Y1, Y4
	BLK_MASK64(Y2, Y4, R13)

	VPCMPEQB Y14, Y0, Y2
	VPCMPEQB Y14, Y1, Y4
	BLK_MASK64(Y2, Y4, R15)

	VPOR     h1blk20<>(SB), Y0, Y2
	VPCMPEQB h1blkc<>(SB), Y2, Y3
	VPCMPEQB h1blke<>(SB), Y2, Y4
	VPOR     Y4, Y3, Y3
	VPCMPEQB h1blkh<>(SB), Y2, Y4
	VPOR     Y4, Y3, Y3
	VPCMPEQB h1blkt<>(SB), Y2, Y4
	VPOR     Y4, Y3, Y3
	VPOR     h1blk20<>(SB), Y1, Y2
	VPCMPEQB h1blkc<>(SB), Y2, Y15
	VPCMPEQB h1blke<>(SB), Y2, Y4
	VPOR     Y4, Y15, Y15
	VPCMPEQB h1blkh<>(SB), Y2, Y4
	VPOR     Y4, Y15, Y15
	VPCMPEQB h1blkt<>(SB), Y2, Y4
	VPOR     Y4, Y15, Y15
	BLK_MASK64(Y3, Y15, R8)

	MOVQ DX, BX
	SHLQ $1, BX
	ORQ  R9, BX
	XORQ R13, BX
	ORQ  BX, R12
	MOVQ DX, R9
	SHRQ $63, R9

	MOVQ R13, BX
	SHLQ $1, BX
	ORQ  R10, BX
	ANDQ 64(SP), BX
	MOVQ R13, R10
	SHRQ $63, R10
	MOVQ BX, (DI)
	ANDQ BX, R8
	MOVQ R8, 256(DI)

	MOVQ R14, R13
	NOTQ R13
	ANDQ BX, R13
	ORQ  R13, R12

	ANDQ    R14, BX
	BTQ     $0, R11
	ADCQ    R14, BX
	SETCS   R11B
	MOVBQZX R11B, R11
	MOVQ    R14, R13
	NOTQ    R13
	ANDQ    R13, BX
	MOVQ    BX, 128(DI)
